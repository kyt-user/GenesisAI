"""Agent 层与 core 实现之间的端口契约（只描述“需要什么”，不定义“怎么做”）。"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable
from genesisai.shared.session import SessionRecord


@runtime_checkable
class PromptPort(Protocol):
    """拿到当前轮次的系统提示与上下文消息，并推断任务协议集合。"""

    def protocols_for(self, text: str) -> list: ...

    def route(self, text: str, active_task=None, previous=None) -> dict: ...

    def is_development_continuation(self, text: str, active_task) -> bool: ...

    def accepts_default_plan(self, text: str) -> bool: ...

    def requests_development_execution(self, text: str, protocols) -> bool: ...


@runtime_checkable
class ContextPort(Protocol):
    """Build and budget a projection without changing authoritative history."""

    def build(
        self, profile: str, *, recovery: bool = False, final: bool = False
    ) -> list: ...
    def prepare(self, messages, tools, *, mode="auto") -> list: ...
    def working_messages(self) -> list: ...
    def compact(self, *, force=False, mode="auto") -> dict: ...


@runtime_checkable
class TaskPort(Protocol):
    """结构化任务状态端口。"""

    def begin_task(self, objective, *, run_id=None, instruction=None, new_task=False,
                   constraint_changes=None, execution_requested=True) -> dict: ...

    def effective_constraints(self, task, run_id) -> dict: ...

    def observe(
        self, observations: list[dict], *, call_id: str | None = None
    ) -> None: ...

    def active_task(self) -> dict | None: ...

    def finish(self, status: str, answer: str = "") -> None: ...


@runtime_checkable
class ToolPort(Protocol):
    """拿到工具定义、执行调用并记录结果。"""

    def prepare_turn(self) -> None: ...
    def bind_model(self, model) -> None: ...

    def deliver_observations(
        self, observations: list[dict], *, call_id: str
    ) -> None: ...

    def definitions(self, *, names=None) -> list: ...
    def completion_issue(self) -> str | None: ...
    def model_content(self, call, result): ...
    def inventory(self) -> dict: ...

    def submission_batch(self, calls): ...

    def execute(self, call: dict, approved: str | None = None) -> dict: ...

    def error(
        self, call: dict, code: str, message: str, retryable: bool = False
    ) -> dict: ...

    def cancel_question(self, call: dict, result: dict) -> None: ...

    def reject(self, call: dict) -> dict: ...

    def confirmation_message(self, name: str) -> str: ...


@runtime_checkable
class SessionPort(Protocol):
    """会话持久化与脱敏事件记录端口。"""

    @property
    def record(self) -> SessionRecord: ...

    def commit(self) -> None: ...

    def event(self, kind: str, **metadata) -> None: ...

    def get_logger(self) -> Any: ...


@runtime_checkable
class DevelopmentPort(Protocol):
    """开发验证策略端口：判定验证时机并驱动验证/必须写工具的恢复流程。"""

    def should_auto_verify(self, state: dict) -> bool: ...

    def requires_change_verification(
        self, result: dict, *, run_state: dict | None = None
    ) -> bool: ...

    def inject_verification_test(self, runner: Any) -> Any: ...
